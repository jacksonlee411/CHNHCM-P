func TestTimelineLongCancellationBudget(t *testing.T) {
	// A long current timeline, not merely many historical versions. No business row cap.
	b := make([]Record, 120000)
	start, _ := time.Parse("2006-01-02", "2020-01-01")
	for i := range b {
		date := start.AddDate(0, 0, i).Format("2006-01-02")
		end := ""
		if i+1 < len(b) {
			end = start.AddDate(0, 0, i+1).Format("2006-01-02")
		}
		typ := "CHANGE"
		if i == 0 {
			typ = "CREATE"
		}
		b[i] = Record{ID: fmt.Sprint(i), Revision: "r", Date: date, End: end, Type: typ, State: "active", Data: BUData{Name: "A"}}
	}
	var maximum time.Duration
	for i := 0; i < 5; i++ {
		ctx, cancel := context.WithCancel(context.Background())
		done := make(chan error, 1)
		go func() {
			_, e := Calculate(ctx, b, "0", "2020-01-01", []Item{{ID: "fix", Action: "CORRECT", RecordID: "0", ExpectedRevision: "r", Changes: PatchFromFields(map[string]*string{"name": textValue("B")})}})
			done <- e
		}()
		time.Sleep(time.Millisecond)
		at := time.Now()
		cancel()
		e := <-done
		elapsed := time.Since(at)
		if !errors.Is(e, context.Canceled) {
			t.Fatalf("cancel: %v", e)
		}
		if elapsed > maximum {
			maximum = elapsed
		}
		if elapsed > time.Second {
			t.Fatalf("cancellation exceeded 1s: %s", elapsed)
		}
	}
	t.Logf("120000 current records; 5 cancellations; max local stop=%s (<1s)", maximum)
}

func TestTimelineThreeBusinessDaysIndependentExpected(t *testing.T) {
	for _, tc := range []struct{ suffix, day, initialStatus, addedName string }{{"P", "2026-03-02", "active", "新"}, {"T", "2026-03-01", "active", "新"}, {"F", "2026-02-28", "not_effective", "甲"}} {
		t.Run(tc.suffix, func(t *testing.T) {
			_, first, e := CreateTimeline(context.Background(), Create{Code: "DAY", Name: "甲", NameEn: textValue("Alpha"), EffectiveDate: "2026-03-01", OperationType: "CREATE", OperationReason: "NEW_ORGANIZATION"}, "2025-01-01")
			if e != nil {
				t.Fatal(e)
			}
			if StatusAt(first.Records, tc.day) != tc.initialStatus {
				t.Fatalf("first %s", tc.day)
			}
			c, e := Calculate(context.Background(), baseline(), "first", "2025-01-01", []Item{{ID: "new", Action: "ADD", Date: "2026-03-01", Type: "CHANGE", Reason: "NAME_ADJUSTMENT", Changes: PatchFromFields(map[string]*string{"name": textValue("新")})}})
			if e != nil {
				t.Fatal(e)
			}
			r := FactAt(c.Records, tc.day)
			if r == nil || r.Data.Name != tc.addedName || *r.Data.NameEn != "Alpha" {
				t.Fatal("today/future arrangement advanced or misinherited")
			}
			c, e = Calculate(context.Background(), c.Records, "first", "2025-01-01", []Item{{ID: "fix", Action: "CORRECT", RecordID: "first", ExpectedRevision: "r1", Changes: PatchFromFields(map[string]*string{"name": textValue("甲2")})}})
			if e != nil {
				t.Fatal(e)
			}
			if c.Records[1].Data.Name != "新" || c.Records[2].Data.Name != "乙" || c.Records[3].Data.Name != "丙" {
				t.Fatal("correction propagated")
			}
		})
	}
	for _, date := range []string{"0001-01-01", "9999-12-31"} {
		_, c, e := CreateTimeline(context.Background(), Create{Code: "EXTREME", Name: "极值", EffectiveDate: date, OperationType: "CREATE", OperationReason: "NEW_ORGANIZATION"}, "0001-01-01")
		if e != nil || c.Records[0].End != "" || StatusAt(c.Records, date) != "active" {
			t.Fatal("open end/date extreme")
		}
	}
}

func TestTimelineTailAndLifecycleFixtureParameters(t *testing.T) {
	for _, day := range []string{"2026-02-28", "2026-03-01", "2026-03-02"} {
		base := baseline()[:1]
		base[0].End = ""
		c, e := Calculate(context.Background(), base, "first", "2025-01-01", []Item{{ID: "tail", Action: "ADD", Date: "2026-03-01", Type: "CHANGE", Reason: "NAME_ADJUSTMENT", Changes: PatchFromFields(map[string]*string{"name": textValue("新")})}})
		if e != nil {
			t.Fatal(e)
		}
		if c.Records[0].End != "2026-03-01" || c.Records[1].End != "" {
			t.Fatal("tail period")
		}
		want := "新"
		if day < "2026-03-01" {
			want = "甲"
		}
		if FactAt(c.Records, day).Data.Name != want {
			t.Fatal("tail advanced early")
		}
	}
	b := []Record{
		{ID: "first", Revision: "f", Date: "2026-01-01", End: "2026-04-01", Type: "CREATE", State: "active", Data: BUData{Name: "甲", NameEn: textValue("Alpha")}},
		{ID: "s1", Revision: "s1r", Date: "2026-04-01", End: "2026-08-01", Type: "DEACTIVATE", State: "inactive", InheritedRecord: "first", InheritedRevision: "f", Data: BUData{Name: "甲", NameEn: textValue("Alpha")}},
		{ID: "r1", Revision: "r1r", Date: "2026-08-01", End: "2026-10-01", Type: "REACTIVATE", State: "active", Data: BUData{Name: "乙", NameEn: textValue("Beta")}},
		{ID: "c2", Revision: "c2r", Date: "2026-10-01", End: "2026-12-01", Type: "CHANGE", State: "active", Data: BUData{Name: "丙", NameEn: textValue("Gamma")}},
		{ID: "s2", Revision: "s2r", Date: "2026-12-01", Type: "DEACTIVATE", State: "inactive", InheritedRecord: "c2", InheritedRevision: "c2r", Data: BUData{Name: "丙", NameEn: textValue("Gamma")}},
	}
	for _, v := range []struct{ date, name, en string }{{"2026-03-31", "甲", "Alpha"}, {"2026-04-01", "甲", "Alpha"}, {"2026-07-31", "甲", "Alpha"}, {"2026-08-01", "乙", "Beta"}, {"2026-09-30", "乙", "Beta"}, {"2026-10-01", "丙", "Gamma"}, {"2026-12-01", "丙", "Gamma"}} {
		r := FactAt(b, v.date)
		if r.Data.Name != v.name || *r.Data.NameEn != v.en {
			t.Fatal("half-open fixture boundary")
		}
	}
	for _, date := range []string{"2026-03-01", "2026-09-01"} {
		c, e := Calculate(context.Background(), b, "first", "2025-01-01", []Item{{ID: "new", Action: "ADD", Date: date, Type: "CHANGE", Reason: "NAME_ADJUSTMENT", Changes: PatchFromFields(map[string]*string{"name": textValue("新")})}})
		if e != nil {
			t.Fatal(e)
		}
		if FactAt(c.Records, date).Data.Name != "新" || FactAt(c.Records, "2026-10-01").Data.Name != "丙" {
			t.Fatal("independent later snapshot")
		}
		if date == "2026-03-01" && (FactAt(c.Records, "2026-04-01").Data.Name != "新" || *FactAt(c.Records, "2026-08-01").Data.NameEn != "Beta") {
			t.Fatal("inactive inheritance or reactivation independence")
		}
	}
	for _, date := range []string{"2026-04-01", "2026-06-01", "2026-08-01", "2026-12-01"} {
		_, e := Calculate(context.Background(), b, "first", "2025-01-01", []Item{{ID: "new", Action: "ADD", Date: date, Type: "CHANGE", Reason: "NAME_ADJUSTMENT", Changes: PatchFromFields(map[string]*string{"name": textValue("新")})}})
		if e == nil {
			t.Fatal("occupied/inactive allowed", date)
		}
	}
}
