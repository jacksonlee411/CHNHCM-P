func textValue(v string) *string { return &v }
func baseline() []Record {
	return []Record{
		{ID: "first", Revision: "r1", RevisionNo: 1, Date: "2026-01-01", End: "2026-06-01", Type: "CREATE", Reason: "NEW_ORGANIZATION", State: "active", Data: BUData{Name: "甲", NameEn: textValue("Alpha")}},
		{ID: "june", Revision: "r2", RevisionNo: 1, Date: "2026-06-01", End: "2026-10-01", Type: "CHANGE", Reason: "NAME_ADJUSTMENT", State: "active", Data: BUData{Name: "乙", NameEn: textValue("Beta")}},
		{ID: "oct", Revision: "r3", RevisionNo: 1, Date: "2026-10-01", Type: "CHANGE", Reason: "NAME_ADJUSTMENT", State: "active", Data: BUData{Name: "丙", NameEn: textValue("Gamma")}},
	}
}
func TestTimelineIndependentSnapshots(t *testing.T) {
	base := baseline()
	copyBase := baseline()
	c, e := Calculate(context.Background(), base, "first", "2025-01-01", []Item{{ID: "new", Action: "ADD", Date: "2026-03-01", Type: "CHANGE", Reason: "NAME_ADJUSTMENT", Changes: PatchFromFields(map[string]*string{"name": textValue("新")})}})
	if e != nil {
		t.Fatal(e)
	}
	// Handwritten independent expected facts/periods, never generated by Calculate.
	want := []struct{ date, end, name, en string }{{"2026-01-01", "2026-03-01", "甲", "Alpha"}, {"2026-03-01", "2026-06-01", "新", "Alpha"}, {"2026-06-01", "2026-10-01", "乙", "Beta"}, {"2026-10-01", "", "丙", "Gamma"}}
	for i, w := range want {
		r := c.Records[i]
		if r.Date != w.date || r.End != w.end || r.Data.Name != w.name || r.Data.NameEn == nil || *r.Data.NameEn != w.en {
			t.Fatalf("%d: %+v", i, r)
		}
	}
	if !reflect.DeepEqual(c.Impact.DataAffectedRanges, []Range{{Start: "2026-03-01", End: textValue("2026-06-01")}}) {
		t.Fatalf("impact %+v", c.Impact)
	}
	c2, e := Calculate(context.Background(), c.Records, "first", "2025-01-01", []Item{{ID: "fix", Action: "CORRECT", RecordID: "first", ExpectedRevision: "r1", Changes: PatchFromFields(map[string]*string{"name": textValue("甲2")})}})
	if e != nil {
		t.Fatal(e)
	}
	if c2.Records[0].Data.Name != "甲2" || c2.Records[1].Data.Name != "新" || *c2.Records[1].Data.NameEn != "Alpha" || c2.Records[2].Data.Name != "乙" || *c2.Records[2].Data.NameEn != "Beta" || c2.Records[3].Data.Name != "丙" {
		t.Fatal(c2.Records)
	}
	if !reflect.DeepEqual(base, copyBase) {
		t.Fatal("mutated original source")
	}
}
func TestTimelineRuleMatrix(t *testing.T) {
	cases := []struct {
		name, date, typ, reason, field string
		value                          *string
		code                           string
		nochange                       bool
	}{
		{"past", "2026-03-01", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("新"), "", false},
		{"today", "2026-06-15", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("新"), "", false},
		{"future", "2026-12-01", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("新"), "", false},
		{"same-day", "2026-06-01", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("乙"), "M02_DATE_CONFLICT", false},
		{"before-first", "2025-12-31", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("新"), "M02_FIRST_RECORD_PROTECTED", false},
		{"outside-enterprise", "2024-12-31", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("新"), "M02_INVALID_INPUT", false},
		{"nochange", "2026-03-01", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("甲"), "", true},
		{"clear-english", "2026-03-01", "CHANGE", "NAME_ADJUSTMENT", "nameEn", nil, "", false},
		{"null-name", "2026-03-01", "CHANGE", "NAME_ADJUSTMENT", "name", nil, "M02_INVALID_INPUT", false},
		{"forbidden", "2026-03-01", "CHANGE", "NAME_ADJUSTMENT", "state", textValue("active"), "M02_FORBIDDEN_INPUT", false},
		{"bad-reason", "2026-03-01", "CHANGE", "NEW_ORGANIZATION", "name", textValue("x"), "M02_INVALID_INPUT", false},
		{"bad-type", "2026-03-01", "CREATE", "NAME_ADJUSTMENT", "name", textValue("x"), "M02_INVALID_INPUT", false},
		{"invalid-day", "2026-02-29", "CHANGE", "NAME_ADJUSTMENT", "name", textValue("x"), "M02_INVALID_INPUT", false},
	}
	for _, v := range cases {
		t.Run(v.name, func(t *testing.T) {
			c, e := Calculate(context.Background(), baseline(), "first", "2025-01-01", []Item{{ID: "item", Action: "ADD", Date: v.date, Type: v.typ, Reason: v.reason, Changes: PatchFromFields(map[string]*string{v.field: v.value})}})
			var f *foundation.Fault
			if v.code != "" {
				if !errors.As(e, &f) || f.Code != v.code {
					t.Fatalf("%v", e)
				}
				return
			}
			if e != nil || c.NoChange != v.nochange {
				t.Fatalf("%v nochange=%v", e, c.NoChange)
			}
			if v.field == "nameEn" && c.Records[1].Data.NameEn != nil {
				t.Fatal("explicit null not cleared")
			}
		})
	}
	// Corrections preserve identity, date and original classification, including same-value declarations.
	for _, target := range []int{0, 1, 2} {
		for _, value := range []string{"改", "甲", "乙", "丙"} {
			b := baseline()
			c, e := Calculate(context.Background(), b, "first", "2025-01-01", []Item{{ID: "fix", Action: "CORRECT", RecordID: b[target].ID, ExpectedRevision: b[target].Revision, Changes: PatchFromFields(map[string]*string{"name": &value})}})
			if e != nil {
				t.Fatal(e)
			}
			r := c.Records[target]
			if r.Date != b[target].Date || r.ID != b[target].ID || r.Type != b[target].Type || r.Reason != b[target].Reason || c.NoChange != (value == b[target].Data.Name) {
				t.Fatal("correction invariant")
			}
		}
	}
}
