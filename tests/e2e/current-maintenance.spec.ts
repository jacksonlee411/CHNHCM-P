import {test, expect, openMoreActions, applyListOption} from './fixtures';
import {open, create, add, read, select} from './bu-support';

test('TL387/389 今日列表不提前采用未来更名，详情始终表达所选记录', async ({page}) => {
  await open(page);
  const code = await create(page);
  await add(page, '9998-01-01', '未来乙');
  await expect(page.getByRole('heading', {name: code + ' · 未来乙', exact: true})).toBeVisible();
  await expect(page.getByText('所选记录尚未生效。', {exact: true})).toBeVisible();
  await expect(page.getByText(/当日状态：/)).toHaveCount(0);
  const id = new URL(page.url()).pathname.split('/').at(-1)!;
  const future = (await read(page)).timeline.find((r: {effectiveDate: string}) => r.effectiveDate === '9998-01-01');
  expect(new URL(page.url()).searchParams.get('selectedRecordId')).toBe(future.recordId);
  await page.getByRole('link', {name: '返回列表', exact: true}).click();
  await page.getByLabel('搜索编码或名称').fill(code);
  await page.getByRole('button', {name: '查询', exact: true}).click();
  const row = page.getByRole('row').filter({hasText: code});
  await expect(row).toContainText('甲');
  await expect(row).not.toContainText('未来乙');
  await expect(row).toContainText('启用');
  await openMoreActions(page);
  await expect(page.getByRole('menuitem', {name: '查看日期…', exact: true})).toHaveCount(0);
  await page.keyboard.press('Escape');
  await row.getByRole('link').click();
  await expect(page.getByRole('heading', {name: code + ' · 甲', exact: true})).toBeVisible();
  await expect(page.getByText('所选记录尚未生效。', {exact: true})).toHaveCount(0);
  await select(page, '9998-01-01');
  await page.reload();
  await expect(page.getByRole('heading', {name: code + ' · 未来乙', exact: true})).toBeVisible();
  expect(await page.evaluate(async id => (await fetch('/api/v1/business-units/' + id + '?businessAt=9998-01-01')).status, id)).toBe(400);
  expect(await page.evaluate(async () => (await fetch('/api/v1/business-units?businessAt=9998-01-01')).status)).toBe(400);
});

test('TL388 未来首条默认可发现，状态筛选和导出同列表，进入后定位未来首条', async ({page}) => {
  await open(page);
  const code = await create(page, '9998-02-01');
  await expect(page.getByText('所选记录尚未生效。', {exact: true})).toBeVisible();
  await expect(page.locator('.object-detail-field').filter({has: page.getByText('状态', {exact: true})})).toContainText('启用');
  await page.getByRole('link', {name: '返回列表', exact: true}).click();
  await page.getByLabel('搜索编码或名称').fill(code);
  await page.getByRole('button', {name: '查询', exact: true}).click();
  const row = page.getByRole('row').filter({hasText: code});
  await expect(row).toHaveCount(1);
  await expect(row).toContainText('未生效');
  await expect(row).toContainText('9998-02-01');
  await applyListOption(page, '状态', '启用');
  await expect(row).toHaveCount(0);
  await applyListOption(page, '状态', '未生效');
  await expect(row).toHaveCount(1);
  await page.getByRole('checkbox', {name: '全选查询结果', exact: true}).check();
  await expect(page.getByRole('button', {name: '导出所选', exact: true})).toBeEnabled();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', {name: '导出所选', exact: true}).click();
  const download = await downloading;
  const stream = await download.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain(code + ',甲,未生效,9998-02-01');
  await row.getByRole('link').click();
  await expect(page.getByText('所选记录尚未生效。', {exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: '9998-02-01', exact: true})).toHaveAttribute('aria-current', 'date');
  expect(new URL(page.url()).searchParams.has('businessAt')).toBe(false);
  await page.screenshot({path: '.local/current-maintenance-future.png', mask: [page.locator('.app-account-name')]});
});
