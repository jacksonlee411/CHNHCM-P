#!/usr/bin/env python3
"""Generate the BU name profile from pinned, offline Unicode 15.0.0 data."""
import argparse
import hashlib
from pathlib import Path
import subprocess
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
DOMAIN = ROOT / "internal/contexts/organization/domain"
SOURCES = {
    "DerivedJoiningType.txt": "c4870b11e2b8b7d0eb70b99ce85608e5c28a399efa316cca97238a58ae160e5e",
    "emoji-data.txt": "29071dba22c72c27783a73016afb8ffaeb025866740791f9c2d0b55cc45a3470",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    groups = {p: [] for p in ["Extended_Pictographic", "D", "L", "R", "T"]}
    with ZipFile(DOMAIN / "testdata/unicode-15.0.0.zip") as archive:
        sources = {name: archive.read(name) for name in SOURCES}
    for filename, digest in SOURCES.items():
        data = sources[filename]
        if hashlib.sha256(data).hexdigest() != digest:
            raise SystemExit(f"Unicode source hash mismatch: {filename}")
        for line in data.decode().splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            interval, prop = [part.strip() for part in line.split(";")]
            if prop not in groups:
                continue
            points = interval.split("..")
            groups[prop].append((int(points[0], 16), int(points[-1], 16)))
    code = """// Code generated by scripts/generate-name-tables.py; DO NOT EDIT.
// Unicode 15.0.0, © 2022 Unicode, Inc. See docs/reference/licenses/unicode-LICENSE.txt.
// Sources: https://www.unicode.org/Public/15.0.0/ucd/extracted/DerivedJoiningType.txt
// and https://www.unicode.org/Public/15.0.0/ucd/emoji/emoji-data.txt.
package foundation

const NameUnicodeVersion = "15.0.0"
type nameRuneSpan struct { lo, hi rune }
"""
    for prop, ranges in groups.items():
        merged = []
        for lo, hi in sorted(ranges):
            if merged and lo <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
            else:
                merged.append((lo, hi))
        code += f"\nvar nameUnicode{prop} = []nameRuneSpan{{\n"
        code += "".join(f"{{0x{lo:X}, 0x{hi:X}}},\n" for lo, hi in merged)
        code += "}\n"
    formatted = subprocess.run(["gofmt"], input=code, text=True, capture_output=True, check=True).stdout
    target = ROOT / "internal/foundation/name_tables.go"
    if args.check:
        if not target.exists() or target.read_text() != formatted:
            raise SystemExit("BU Unicode tables are stale; run make generate")
    else:
        target.write_text(formatted)


if __name__ == "__main__":
    main()
